/* 해당 영역에 걸리는 신살만 문장으로 */
function salFor(s, domain) {
  return s.shinsal
    .filter(k => SHINSAL_DESC[k] && SHINSAL_DESC[k].dom.includes(domain))
    .map(k => `<b>${k}</b>. ${SHINSAL_DESC[k].t}`);
}

