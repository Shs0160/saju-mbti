/* ---------- 한국어 조사 ---------- */
function jong(w) {
  const s = String(w).trim();
  const ch = s.charCodeAt(s.length - 1);
  if (ch < 0xAC00 || ch > 0xD7A3) return -1;
  return (ch - 0xAC00) % 28;
}
function W(w, pair) {
  const [withB, without] = pair.split('/');
  const j = jong(w);
  if (pair === '으로/로') return w + (j === 0 || j === 8 || j === -1 ? '로' : '으로');
  return w + (j > 0 ? withB : without);
}

