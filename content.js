  const grp = s.gender === 'M' ? '재성' : '관성';
  const spans = s.daeun
    .filter(d => GOD_GROUP_OF[ENGINE.tenGod(s.dayGan, d.gan)] === grp)
    .map(d => ({ from: d.age, to: d.age + 9 }))
    .filter(w => w.to >= 15 && w.from <= 55);
