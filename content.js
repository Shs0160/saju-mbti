/* 우선순위: 격국(월지) > 십신 분포 > 오행 비율 > 신살 */
const AXIS_W = { 격국: 0.36, 십신: 0.34, 오행: 0.22, 신살: 0.08 };
const AXIS_SCALE = { 격국: 1.0, 십신: 2.55, 오행: 2.7, 신살: 1.4 };
/* 표본 6,000명의 중앙값을 0으로 맞추는 보정값. 없으면 한쪽으로 쏠린다. */
const AXIS_OFFSET = [0.092, -0.043, 0.118, -0.212];
const AXIS_GAIN = 2.0;

function innateAxes(s) {
  const G_ = ENGINE.GAN, J_ = ENGINE.JI;

  /* 1) 격국: 월지 지장간 본기가 일간에게 갖는 십신 */
  const mj = J_[s.pillars.month.ji];
  const bongi = mj.hidden[mj.hidden.length - 1][0];
  const gyeokGod = ENGINE.tenGod(s.dayGan, G_.findIndex(g => g.k === bongi));
  const gyeok = GOD_AXIS[gyeokGod] || [0, 0, 0, 0];

  /* 2) 십신 분포 */
  const gT = Object.values(s.gods).reduce((a, b) => a + b, 0) || 1;
  const dist = [0, 0, 0, 0];
  for (const k in s.gods) {
    const v = GOD_AXIS[k]; if (!v) continue;
    const w = s.gods[k] / gT;
    for (let i = 0; i < 4; i++) dist[i] += v[i] * w;
  }

  /* 3) 오행 비율 */
  const oT = Object.values(s.oheng).reduce((a, b) => a + b, 0) || 1;
  const el = [0, 0, 0, 0];
  for (const k in s.oheng) {
    const v = EL_AXIS[k]; if (!v) continue;
    const w = s.oheng[k] / oT;
    for (let i = 0; i < 4; i++) el[i] += v[i] * w;
  }

  /* 4) 신살 */
  const sh = [0, 0, 0, 0];
  for (const k of s.shinsal) {
    const v = SHIN_AXIS[k]; if (!v) continue;
    for (let i = 0; i < 4; i++) sh[i] += v[i];
  }

  /* 신강약은 방향이 아니라 표현 강도를 정한다 */
  const mul = s.strength === '신강' ? 1.18 : s.strength === '신약' ? 0.85 : 1.0;

  const v = [0, 1, 2, 3].map(i => Math.tanh((
    AXIS_W.격국 * AXIS_SCALE.격국 * gyeok[i]
    + AXIS_W.십신 * AXIS_SCALE.십신 * dist[i]
    + AXIS_W.오행 * AXIS_SCALE.오행 * el[i]
    + AXIS_W.신살 * AXIS_SCALE.신살 * sh[i]
    + AXIS_OFFSET[i]
  ) * AXIS_GAIN * mul));

  return {
    values: v,
    power: v.map(Math.abs),
    code: v.map((x, i) => (x >= 0 ? AXES[i].pos : AXES[i].neg)).join(''),
    gyeok: gyeokGod,
    strengthMul: mul,
  };
}

