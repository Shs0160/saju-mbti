/* 잘 맞는 직업 6개 */
function jobPicks(s, gyeok) {
  const core = GYEOK_CORE[gyeok] || [];
  const yong = EL_JOB[s.yongshin] || [];
  const strong = EL_JOB[s.strongest] || [];
  const out = [];
  const push = (v, why) => { if (v && !out.some(o => o.name === v)) out.push({ name: v, why }); };
  core.forEach(v => push(v, gyeok + '격'));
  yong.slice(0, 3).forEach(v => push(v, '용신 ' + s.yongshin));
  strong.slice(0, 2).forEach(v => push(v, '강한 ' + s.strongest));
  return out.slice(0, 6);
}

/* 결혼 적령기 구간 (15~55세) */
